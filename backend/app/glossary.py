# 짧은 표기가 다른 낱말 안에서 잘못 잡히는 것을 막는다. 앞뒤가 한글이면 낱말의 일부로 본다.
# 예: "업" 이 "사업"·"직업" 에, "법" 이 "방법" 에, "계" 가 "세계" 에 걸리면 안 된다.
# 조사는 붙어도 잡아야 하므로("갈애가", "비구들이여") 뒤쪽은 조사·어미가 허용된다.
_PARTICLES = ("이여", "이다", "이란", "이라", "이며", "에게", "처럼", "부터", "까지", "들",
              "이", "가", "은", "는", "을", "를", "의", "에", "와", "과", "도", "로", "여", "란", "라", "께", "며", "만", "아")


def _is_hangul(ch: str) -> bool:
    return "가" <= ch <= "힣"


def _ends_as_word(after: str) -> bool:
    """term 뒤가 조사(여러 개 겹쳐도)로만 이어지고 끝나는지. "들이여" = "들" + "이여"."""
    for _ in range(3):
        if not after or not _is_hangul(after[0]):
            return True
        nxt = next((p for p in _PARTICLES if after.startswith(p)), None)
        if nxt is None:
            return False
        after = after[len(nxt):]
    return not after or not _is_hangul(after[0])


def _word_boundary(text: str, term: str) -> bool:
    """term 이 text 안에 낱말로 나오는지 (앞은 한글이 아니고, 뒤는 조사거나 한글이 아님)."""
    start = 0
    while True:
        i = text.find(term, start)
        if i < 0:
            return False
        before = text[i - 1] if i > 0 else ""
        if not _is_hangul(before) and _ends_as_word(text[i + len(term):]):
            return True
        start = i + 1


def extract(persona_key: str, text: str, limit: int = 10) -> list[dict]:
    """답변에 등장한 용어를 [{term, meaning}] 로. 본문 등장 순서, 최대 limit 개."""
    table = GLOSSARY.get(persona_key) or {}
    found = []
    for term in sorted(table, key=len, reverse=True):
        if term in text and _word_boundary(text, term):
            found.append(term)
    found.sort(key=text.find)
    return [{"term": t, "meaning": table[t]} for t in found[:limit]]
