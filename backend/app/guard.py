"""생성된 답변이 페르소나 규칙을 지켰는지 검사한다.

왜 코드로 검사하는가 (CLAUDE.md 4.7):
로컬 8B 모델은 같은 프롬프트로도 실행마다 결과가 달라진다. 말투·1인칭·한국어 규칙을
지킬 때도 있고 안 지킬 때도 있다. 프롬프트를 더 손봐도 편차 자체는 없어지지 않는다.
그래서 지키는지를 **매번 확인**하고, 어겼으면 무엇을 어겼는지 알려 주고 다시 쓰게 한다.
안전 경로를 코드로 옮긴 것과 같은 접근이다.

검사만 하고 고치지는 않는다. 후처리로 문장을 바꾸면 근거와 어긋날 수 있다.
"""
import re

# 영어 단어. 규칙 2 — 답변 전체를 한국어로 쓴다.
# 원전 제목·인물명이 영어로 튀어나오는 것("Zarathustra의 웃음")을 잡는다.
_ENGLISH = re.compile(r"[A-Za-z]{2,}")
# 한자·가나. qwen 계열이 "乞者", "今夜" 처럼 섞는다
_CJK = re.compile(r"[一-鿿぀-ヿ]+")

# 자기 자신을 3인칭으로 부르는 것. 규칙 1.
# 이름 자체는 허용한다("나는 니체다"). 뒤에 3인칭 조사·서술이 붙는 경우만 잡는다.
_THIRD_PERSON = {
    "nietzsche": re.compile(r"니체(라면|는\s|가\s|의\s|께서|도\s|에게|와\s같)"),
    "jesus": re.compile(r"예수(님|께서|는\s|가\s|의\s|와\s같)|그리스도(께서|는\s)"),
    # 경전에서 붓다는 자신을 "여래"라 3인칭으로도 부른다. 그것은 허용하고 현대식 호칭만 잡는다
    "buddha": re.compile(r"부처(님|께서|는\s|가\s|의\s|라면)|붓다(께서|는\s|가\s|의\s|라면)|석가모니|세존께서"),
}

# 페르소나별 금지 어미. 문장 끝에서만 본다.
# (정규식, 무엇이 잘못인지, 어떻게 고칠지). 고치는 법을 같이 주지 않으면 8B 는 재생성해도 같은 실수를 반복한다.
# 2026-09-19: 예수 규칙을 뒤집었다 (CLAUDE.md 4.6). 성서의 예수는 "~하라/~하리라/~느니라"로 말하지
# "~습니다/~십시오"로 말하지 않는다. 이전 판은 사극체를 막으려다 성경체까지 막았다.
_BANNED_ENDINGS = {
    # 니체: ~다/~라/~는가/~인가. 존댓말·구어체·사극체 금지
    "nietzsche": [
        (re.compile(r"(습니다|읍니다|입니다|합니다|십니다)[.!?…\"']"), "존댓말",
         '"~습니다/~입니다"를 "~다"로 바꿔라'),
        (re.compile(r"(세요|해요|어요|아요|네요|군요|지요|죠)[.!?…\"']"), "~요체",
         '"~요"로 끝나는 문장을 "~다"로 바꿔라'),
        (re.compile(r"(거든|잖아|야|어\?|지\?)[.!?…\"']"), "구어체",
         '"~거든/~잖아/~야"를 "~다"로 바꿔라'),
        (re.compile(r"(느니라|나이다|하옵|더이다|노라)"), "사극체",
         '"~느니라/~하옵/~노라"를 "~다" 또는 "~하라"로 바꿔라'),
    ],
    # 예수: 개역 성경 어투(~하라/~하리라/~느니라/보라). 존댓말·~요체·구어체 금지
    "jesus": [
        (re.compile(r"(습니다|읍니다|입니다|합니다|십니다|십시오|시오)[.!?…\"']"), "존댓말",
         '"~습니다/~십시오"를 성경 어투("~하라", "~하리라", "~느니라")로 바꿔라'),
        # "무슨 상이 있으리요" 같은 성경체 "~리요" 는 허용 (2026-10-14 — 30문항 평가에서 이걸 잡아 세 번 재생성했다)
        (re.compile(r"(?<!리)(요|죠)[.!?…\"']"), "~요체",
         '"~요/~죠"로 끝나는 문장을 "~하라" 또는 "~느니라"로 바꿔라'),
        (re.compile(r"(거든|잖아|거야|이야|단다)[.!?…\"']"), "구어체",
         '"~거야/~이야/~단다"를 "~하라" 또는 "~느니라"로 바꿔라'),
    ],
    # 부처: 니까야 역본 어투(~이다/~한다/~하라). 존댓말·~요체·구어체 금지. 예수와 어미가 겹쳐도 무방 (사용자 결정)
    "buddha": [
        (re.compile(r"(습니다|읍니다|입니다|합니다|십니다|십시오|시오)[.!?…\"']"), "존댓말",
         '"~습니다/~십시오"를 "~이다", "~한다", "~하라"로 바꿔라'),
        (re.compile(r"(?<!리)(요|죠)[.!?…\"']"), "~요체",
         '"~요/~죠"로 끝나는 문장을 "~이다" 또는 "~하라"로 바꿔라'),
        (re.compile(r"(거든|잖아|거야|이야|단다)[.!?…\"']"), "구어체",
         '"~거야/~이야/~단다"를 "~이다" 또는 "~하라"로 바꿔라'),
    ],
}

# 겸양어. 페르소나가 사용자를 윗사람처럼 대하며 화자가 뒤바뀌는 현상 (CLAUDE.md 7절).
# qwen3.5 계열에서 예수 페르소나가 "저는 당신에게…"로 말하는 경우가 잦았다.
# 세 페르소나 모두 자기를 낮추지 않는다. 니체는 "나", 예수는 "내가/나는", 부처는 "나/여래" 다.
_HUMBLE = re.compile(r"(^|[\s\"'(])(저는|제가|저를|저에게|저와|저의|제게)([\s,]|$)")

# 성경 장절·작품 인용 표기. 규칙 4 — 출처는 시스템이 따로 보여준다.
_CITATION = re.compile(r"\(\s*(마태복음|마가복음|누가복음|마태|마가|누가|마|막|눅|차라투스트라|법구경|숫타니파타|우다나)[^)]*\d+[:：.]\d+[^)]*\)|\d+장\s*\d+절|\d+번째\s*게송")

# 길이. 규칙 4 는 600자 이내지만 실측상 8B 는 거의 지키지 못한다.
# 너무 빡빡하면 재생성만 반복하므로 "명백히 길다" 선에서 자른다.
_MAX_CHARS = 500          # 3~5문장 목표. 이전 1,000 은 4~5문단 답변을 허용해 버렸다
_MAX_PARAGRAPHS = 3
# 근거 없음 경로는 예전엔 두 문장(200자)이었으나, 2026-10-12 부터 찬반을 말하므로 같은 한도를 쓴다 (CLAUDE.md 4.3)


def check(persona_key: str, text: str, *, safety: bool,
          must_include: str | None = None, must_not_include: str | None = None) -> list[str]:
    """어긴 규칙을 한국어 설명으로 돌려준다. 빈 리스트면 통과.
    must_include: 반드시 들어가야 할 말 (사이비 질문에 예수의 "거짓 선지자").
    must_not_include: 시스템이 이미 앞에 붙이는 문장 (근거 없음 경로의 첫 문장) — 모델이 또 쓰면 두 번 나온다."""
    bad: list[str] = []

    if must_include and must_include not in text:
        bad.append(f'"{must_include}"라는 말이 빠졌다. 반드시 넣어라')
    if must_not_include and must_not_include in text:
        bad.append(f'"{must_not_include}"라는 말은 쓰지 마라. 붙일지는 시스템이 정한다. 그 말을 빼고 다시 써라')

    m = _ENGLISH.search(text)
    if m:
        bad.append(f'영어 단어를 썼다("{m.group(0)}"). 한국어 표기로 바꿔라')

    m = _CJK.search(text)
    if m:
        bad.append(f'한자를 썼다("{m.group(0)}"). 한글로 바꿔라')

    tp = _THIRD_PERSON.get(persona_key)
    if tp:
        m = tp.search(text)
        if m:
            bad.append(f'자기를 3인칭으로 불렀다("{m.group(0).strip()}"). 너가 본인이므로 "나"로 말하라')

    for pattern, label, howto in _BANNED_ENDINGS.get(persona_key, []):
        m = pattern.search(text)
        if m:
            bad.append(f'{label}를 썼다("{m.group(0)}"). {howto}')
            break           # 말투 지적은 하나면 충분하다

    m = _HUMBLE.search(text)
    if m:
        bad.append(f'자기를 낮추는 겸양어를 썼다("{m.group(2)}"). '
                   f'상대가 윗사람이 아니다. "저/제가"를 "나/내가"로 바꿔라')

    # 시스템이 준 재료를 드러내는 말. "그대가 제시한 구절들에 따르면"처럼 사용자가 구절을 준 것처럼 말했다 (2026-10-12)
    if "구절" in text:
        bad.append('"구절"이라는 말을 썼다. 시스템이 준 재료를 드러내지 말고 네 말과 네 글로 말하라')

    m = _CITATION.search(text)
    if m:
        bad.append(f'출처 표기를 적었다("{m.group(0)}"). 장절 번호를 쓰지 마라')

    if safety:
        return bad          # 안전 경로는 길이를 따지지 않는다 (앞에 고정 문구가 붙는다)

    if len(text) > _MAX_CHARS:
        bad.append(f"너무 길다({len(text)}자). 3~5문장으로 줄여라")
    elif text.count("\n\n") + 1 > _MAX_PARAGRAPHS:
        bad.append("문단이 너무 많다. 3~5문장으로 줄여라")

    return bad


def retry_message(violations: list[str]) -> str:
    """재생성 지시. 무엇을 어겼는지 그대로 알려준다."""
    items = "\n".join(f"- {v}" for v in violations)
    return (f"방금 답변이 규칙을 어겼다:\n{items}\n\n"
            f"**내용과 구성은 그대로 두고 지적된 부분만 고쳐서** 답변 전체를 다시 써라.\n"
            f"특히 모든 문장의 끝을 하나하나 확인하라. 한 문장이라도 남아 있으면 실패다.\n"
            f"고쳤다는 설명이나 사과는 쓰지 말고 답변 본문만 써라.")
